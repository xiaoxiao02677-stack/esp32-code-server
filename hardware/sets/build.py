def choose_board(boards: list[dict[str, Any]]) -> Optional[dict[str, Any]]:
    if not sys.stdin.isatty():
        notice_bad("当前不是交互式终端，请用 --board <id> 指定版型")
        return None

    total = len(boards)
    for attempt in range(3):
        try:
            answer = input(f"请输入编号或版型 id（1-{total}，q 退出）: ").strip()
        except EOFError:
            say("")
            notice_bad("没有读到输入，已退出")
            return None
        if answer.lower() in {"q", "quit", "exit"}:
            say("已取消。")
            return None
        if answer.isdigit():
            index = int(answer)
            if 1 <= index <= total:
                return boards[index - 1]
        else:
            for board in boards:
                if board["id"] == answer:
                    return board
        say(f"{red('[错误]')} 输入无效：{answer!r}，请输入 1-{total} 之间的编号或版型 id")
    notice_bad("连续 3 次输入无效，已退出（重新运行本脚本即可）")
    return None


def confirm_board(board: dict[str, Any], assume_yes: bool) -> bool:
    say()
    say(rule("="))
    say(f"已选择版型: {bold(board['id'])} — {board['name']}")
    say(f"  目标芯片 : {board['target']}")
    say(f"  同步目录 : main/boards/{board['board_dir']}")
    say(f"  Kconfig  : CONFIG_{board['kconfig_symbol']}")
    if board.get("notes"):
        say(f"  注意要点 : {board['notes']}")
    say(rule("="))

    if board["pins_verified"]:
        return True
    say()
    notice_warn(red("该版型引脚未经实物核实（pins_verified=false）"))
    if assume_yes:
        # 这里可能是编译，也可能是 --sync-only 只做同步，文案保持中性
        say("已指定 --yes，跳过二次确认，继续执行。")
        return True
    if not sys.stdin.isatty():
        notice_bad("引脚未验证且非交互式终端，请加 --yes 明确确认后重试")
        return False
    try:
        answer = input("该版型引脚未经实物核实，烧录可能变砖，确认继续？[y/N] ").strip()
    except EOFError:
        say("")
        return False
    return answer.lower() in {"y", "yes"}


