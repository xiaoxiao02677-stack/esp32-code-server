def collect_sync_files(source: Path) -> list[Path]:
    files: list[Path] = []
    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        if any(part.startswith(".") or part == "__pycache__" for part in path.relative_to(source).parts):
            continue
        if path.name.lower() in SYNC_EXCLUDE_NAMES:
            continue
        if path.suffix.lower() not in SYNC_SUFFIXES:
            continue
        files.append(path)
    return files


def sync_board(board: dict[str, Any], fw_root: Path) -> Path:
    source: Path = board["_dir"]
    target = fw_root / "main" / "boards" / Path(board["board_dir"])
    say()
    say(bold(f"[1/4] 同步版型文件  {source} -> {target}"))

    files = collect_sync_files(source)
    if not files:
        notice_warn(f"{source} 下没有可同步的 *.c/*.cc/*.h/*.json 文件（README.md 与 set.json 不同步）")

    target.mkdir(parents=True, exist_ok=True)
    plan: list[tuple[Path, Path, str]] = []
    for path in files:
        destination = target / path.relative_to(source)
        if destination.exists():
            try:
                newer = path.stat().st_mtime > destination.stat().st_mtime + 1
            except OSError:
                newer = True
            plan.append((path, destination, "更新" if newer else "跳过(无变化)"))
        else:
            plan.append((path, destination, "新增"))

    say("  将要写入的文件：")
    for path, destination, action in plan:
        say(f"    {action:<14} {path.relative_to(source).as_posix()}")

    copied = 0
    for path, destination, action in plan:
        if action == "跳过(无变化)":
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        copied += 1
    say(f"  同步完成：写入 {copied} 个文件，跳过 {len(plan) - copied} 个")

    known = {path.resolve() for path in files}
    stale = [
        path for path in sorted(target.rglob("*"))
        if path.is_file()
        and path.suffix.lower() in SYNC_SUFFIXES
        and path.name != "sets-build.json"
        and (source / path.relative_to(target)).resolve() not in known
    ]
    if stale:
        notice_warn("目标目录存在源目录已删除的残留文件（未自动删除，请确认）：")
        for path in stale:
            say(f"    {path}")
    return target


def clean_generated_configs(boards: list[dict[str, Any]], fw_root: Path) -> None:
    """清掉上一轮生成的 sets-build.json，避免 -c 扫描时把别的版型也卷进来。"""
    for board in boards:
        stale = fw_root / "main" / "boards" / Path(board["board_dir"]) / "sets-build.json"
        if stale.is_file():
            stale.unlink()


def write_build_config(target: Path, board: dict[str, Any]) -> tuple[str, list[str]]:
    """把 set.json 的 sdkconfig_append 并入一份 sets-build.json（固件 build.py 用 -c 读取）。

    返回 (传给固件 build.py 的 -c 文件名, 追加的 sdkconfig 行)。
    """
    generated = target / "sets-build.json"
    append = list(board.get("sdkconfig_append") or [])
    if not append:
        if generated.exists():
            generated.unlink()
        return "config.json", []

    config_path = target / "config.json"
    if not config_path.is_file():
        notice_warn(f"缺少 config.json，无法透传 sdkconfig_append：{config_path}")
        if generated.exists():
            generated.unlink()
        return "config.json", []

    try:
        config = _read_json(config_path)
    except Exception as error:  # noqa: BLE001
        notice_warn(f"config.json 解析失败，忽略 sdkconfig_append 透传：{error}")
        if generated.exists():
            generated.unlink()
        return "config.json", []

    builds = config.get("builds")
    if not isinstance(builds, list) or not builds:
        notice_warn(f"config.json 没有 builds 数组，忽略 sdkconfig_append 透传：{config_path}")
        if generated.exists():
            generated.unlink()
        return "config.json", []

    index = next(
        (i for i, item in enumerate(builds)
         if isinstance(item, dict) and item.get("name") == board["build_name"]),
        None,
    )
    if index is None:
        notice_warn(
            f"config.json 中没有 name={board['build_name']!r} 的 build 条目，"
            f"忽略 sdkconfig_append 透传"
        )
        if generated.exists():
            generated.unlink()
        return "config.json", []

    entry = dict(builds[index])
    merged = [str(item) for item in (entry.get("sdkconfig_append") or [])]
    for line in append:
        if line not in merged:
            merged.append(line)
    entry["sdkconfig_append"] = merged
    builds = list(builds)
    builds[index] = entry
    config["builds"] = builds

    write_text_preserve(generated, json.dumps(config, ensure_ascii=False, indent=4) + "\n")
    say(f"  透传 sdkconfig_append：已生成 {generated.name}（{len(append)} 行）")
    for line in append:
        say(f"    + {line}")
    notice_warn("透传的 CONFIG_* 必须是 Kconfig 中真实存在的符号，否则固件 build.py 会报 Kconfig rejected")
    return generated.name, append


