def build_kconfig_block(boards: list[dict[str, Any]]) -> str:
    lines = [BEGIN_LINE]
    for board in boards:
        lines.append(f"    config {board['kconfig_symbol']}")
        lines.append(f'        bool "{board["kconfig_prompt"]}"')
        lines.append(f"        depends on IDF_TARGET_{board['target'].upper()}")
    lines.append(END_LINE)
    return "\n".join(lines) + "\n"


def build_cmake_block(boards: list[dict[str, Any]]) -> str:
    lines = [BEGIN_LINE]
    for board in boards:
        lines.append(f"elseif(CONFIG_{board['kconfig_symbol']})")
        lines.append(f'    set(BOARD_DIR "{board["board_dir"]}")')
        lines.append(f'    set(BUILTIN_TEXT_FONT {board["text_font"]})')
        lines.append(f'    set(BUILTIN_ICON_FONT {board["icon_font"]})')
        lines.append(f"    set(DEFAULT_EMOJI_COLLECTION {board['emoji_collection']})")
        for extra in board.get("cmake_extra") or []:
            lines.append(f"    {extra}")
    lines.append(END_LINE)
    return "\n".join(lines) + "\n"


def _locate_kconfig_insert(text: str) -> int:
    """返回插入偏移：choice BOARD_TYPE 的 endchoice 行首。"""
    start = re.search(r"^choice\s+BOARD_TYPE\s*$", text, re.MULTILINE)
    if not start:
        raise RuntimeError("main/Kconfig.projbuild 中找不到 'choice BOARD_TYPE'")
    end = re.search(r"^endchoice\s*$", text[start.end():], re.MULTILINE)
    if not end:
        raise RuntimeError("'choice BOARD_TYPE' 之后找不到 endchoice")
    return start.end() + end.start()


def _locate_cmake_insert(text: str) -> int:
    """返回插入偏移：board 选择链里 else() 的行首，没有 else() 就用闭合 endif()。

    用 split("\\n") 而不是 splitlines()，保证偏移量与原文一一对应（splitlines 会
    吃掉行尾的 \\r 并额外切分 \\x0b 等字符，导致偏移量错位）。
    """
    lines = text.split("\n")
    start = None
    for index, line in enumerate(lines):
        if re.match(r"^if\(CONFIG_BOARD_TYPE_", line):
            start = index
            break
    if start is None:
        raise RuntimeError("main/CMakeLists.txt 中找不到 board 选择链（if(CONFIG_BOARD_TYPE_...)）")

    depth = 0
    else_index: Optional[int] = None
    end_index: Optional[int] = None
    for index in range(start, len(lines)):
        line = lines[index]
        if re.match(r"^\s*if\b", line):
            depth += 1
        elif re.match(r"^\s*endif\b", line):
            depth -= 1
            if depth <= 0:
                end_index = index
                break
        elif depth == 1 and else_index is None and re.match(r"^\s*else\b", line):
            else_index = index
    if end_index is None:
        raise RuntimeError("board 选择链没有闭合的 endif()")

    insert_line = else_index if else_index is not None else end_index
    return len("\n".join(lines[:insert_line])) + 1 if insert_line else 0


BLOCK_PATTERN = re.compile(
    re.escape(BEGIN_MARKER) + r"[^\n]*\n.*?" + re.escape(END_MARKER) + r"[^\n]*\n?",
    re.DOTALL,
)


def read_text_preserve(path: Path) -> str:
    """读取文本但保留原始换行符（newline=""），避免写回时整份文件被换行符改写。"""
    with path.open("r", encoding="utf-8", newline="") as handle:
        return handle.read()


def write_text_preserve(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write(text)


def upsert_block(path: Path, block: str, locate, label: str) -> bool:
    """把标记块写入 path（已存在就整体替换）。返回文件是否发生变化。"""
    original = read_text_preserve(path)
    # 跟随原文件的换行风格：CRLF 文件就用 CRLF，LF 文件就用 LF
    crlf = original.count("\r\n")
    newline = "\r\n" if crlf and crlf == original.count("\n") else "\n"
    if newline != "\n":
        block = block.replace("\n", newline)
    matched = BLOCK_PATTERN.search(original)
    if matched:
        if matched.group(0) == block:
            say(f"  {label}: 标记块内容已是最新，未改动")
            return False
        new_text = original[:matched.start()] + block + original[matched.end():]
        action = "替换已有标记块"
    else:
        offset = locate(original)
        new_text = original[:offset] + block + newline + original[offset:]
        action = "插入新标记块"

    backup = path.with_suffix(path.suffix + BACKUP_SUFFIX)
    if not backup.exists():
        shutil.copy2(path, backup)
        say(f"  {label}: 已备份原文件 -> {backup.name}")
    write_text_preserve(path, new_text)

    diff = list(difflib.unified_diff(
        original.splitlines(), new_text.splitlines(),
        fromfile=f"{path.name} (原)", tofile=f"{path.name} (新)", lineterm="", n=0,
    ))
    added = sum(1 for line in diff if line.startswith("+") and not line.startswith("+++"))
    removed = sum(1 for line in diff if line.startswith("-") and not line.startswith("---"))
    say(f"  {label}: {action}，新增 {added} 行 / 删除 {removed} 行")
    for line in diff[:40]:
        say(f"    {line}")
    if len(diff) > 40:
        say(f"    ...（diff 共 {len(diff)} 行，已截断）")

    expected = len(original.splitlines()) + added - removed
    actual = len(new_text.splitlines())
    if expected != actual:
        raise RuntimeError(f"{label}: 行数校验失败（期望 {expected}，实际 {actual}），已中止")
    return True


def register_boards(boards: list[dict[str, Any]], fw_root: Path) -> None:
    say()
    say(bold("[2/4] 注册版型到固件（Kconfig / CMakeLists 标记块，幂等）"))

    kconfig_path = fw_root / "main" / "Kconfig.projbuild"
    cmake_path = fw_root / "main" / "CMakeLists.txt"
    for path in (kconfig_path, cmake_path):
        if not path.is_file():
            raise RuntimeError(f"固件文件不存在，请检查 --fw-root 是否指向正确的固件根目录: {path}")

    try:
        upsert_block(kconfig_path, build_kconfig_block(boards), _locate_kconfig_insert, "Kconfig.projbuild")
        upsert_block(cmake_path, build_cmake_block(boards), _locate_cmake_insert, "CMakeLists.txt")
    except RuntimeError as error:
        notice_bad(str(error))
        raise

    notice_ok("注册完成（标记块之外的内容未被改动）")


