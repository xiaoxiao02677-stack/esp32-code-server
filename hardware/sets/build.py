def ensure_components(fw_root: Path) -> None:
    """自带副本缺 managed_components/ 时，先从上游目录借一份（本地拷贝）。

    拷贝远比联网重下 758M 快。上游也没有时交给 IDF 组件管理器联网拉取
    （dependencies.lock 已随副本一起复制，版本可锁定）。
    """
    target = fw_root / "managed_components"
    if target.is_dir() and any(target.iterdir()):
        return
    if fw_root.resolve() != BUNDLED_FW.resolve():
        # 用户显式指定了别的固件根，不擅自往里拷东西
        return
    for candidate in COMPONENT_SOURCE_CANDIDATES:
        source = candidate / "managed_components"
        if source.is_dir() and any(source.iterdir()):
            say()
            say(bold("[准备] 借用第三方组件（本地拷贝，免联网重下 758M）"))
            say(f"  {source}")
            say(f"  ->  {target}")
            try:
                shutil.copytree(source, target, copy_function=shutil.copy2)
            except OSError as error:
                notice_warn(f"借用失败（不影响编译，IDF 会自行联网拉取）: {error}")
                return
            notice_ok("managed_components 已就位")
            return
    notice_warn("managed_components/ 缺失，且上游目录也没有可借用的副本")
    say("        首次编译将联网从 components.espressif.com 拉取（约 758M），请保持网络畅通。")


