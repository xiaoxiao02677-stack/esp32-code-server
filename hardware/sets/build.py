_PROJECT_VER_PATTERN = re.compile(r'^set\(PROJECT_VER\s+"([^"]+)"\)\s*$')

def _read_versions_ini() -> configparser.ConfigParser:
    """读 config.ini。inline_comment_prefixes 让 `version = 2.5.2 # 备注`
    里的行内注释被剥掉（默认行为会连注释一起读进值里）。"""
    parser = configparser.ConfigParser(inline_comment_prefixes=("#", ";"))
    parser.read(VERSIONS_INI, encoding="utf-8")
    return parser


def read_board_version(board_id: str) -> Optional[str]:
    """从 config.ini 读版型版本：[<board_id>] > [default]，都没有返回 None。"""
    if not VERSIONS_INI.is_file():
        return None
    try:
        parser = _read_versions_ini()
    except (configparser.Error, OSError) as error:
        notice_warn(f"config.ini 解析失败，版本号沿用 CMakeLists 现值: {error}")
        return None
    for section in (board_id, "default", "DEFAULT"):
        if parser.has_section(section) and parser.has_option(section, "version"):
            value = parser.get(section, "version").strip()
            if value:
                return value
    return None


def apply_project_version(fw_root: Path, board: dict[str, Any]) -> Optional[str]:
    """构建前把 config.ini 里的版型版本写进 <FW>/CMakeLists.txt 的 PROJECT_VER 行。

    返回实际生效的版本号（写入的值，或文件没动时的现值）。只替换那一行的
    版本字面量，不动文件其余内容与换行风格；缺 config.ini / 缺该版型条目时
    保持现值不动（行为与改造前完全一致）。
    """
    cmake_path = fw_root / "CMakeLists.txt"
    if not cmake_path.is_file():
        notice_warn(f"找不到 {cmake_path}，跳过版本号注入")
        return None

    original = read_text_preserve(cmake_path)
    current: Optional[str] = None
    for line in original.split("\n"):
        stripped = _PROJECT_VER_PATTERN.match(line.strip())
        if stripped:
            current = stripped.group(1)
            break
    if current is None:
        notice_warn(f"{cmake_path} 里没有 set(PROJECT_VER ...) 行，跳过版本号注入")
        return None

    wanted = read_board_version(board["id"])
    if not wanted:
        say(f"  版本号: {current}（config.ini 无 [{board['id']}] 条目，沿用现值）")
        return current
    if wanted == current:
        say(f"  版本号: {current}（与 config.ini 一致，未改动）")
        return current

    def _replace(line: str) -> str:
        if _PROJECT_VER_PATTERN.match(line.strip()):
            return f'set(PROJECT_VER "{wanted}")'
        return line

    new_text = "\n".join(_replace(line) for line in original.split("\n"))
    # 跟随原文件换行风格（read_text_preserve 保留原始 \r\n，join 后需还原）
    if "\r\n" in original:
        new_text = new_text.replace("\n", "\r\n")
    backup = cmake_path.with_suffix(cmake_path.suffix + BACKUP_SUFFIX)
    if not backup.exists():
        shutil.copy2(cmake_path, backup)
    write_text_preserve(cmake_path, new_text)
    say(f"  版本号: {current} -> {wanted}（来自 config.ini [{board['id']}]，已写入 CMakeLists.txt）")
    return wanted


_VERSION_LINE_PATTERN = re.compile(
    r'^(\s*version\s*=\s*)(\S+)(\s*(?:[#;].*)?)$'
)


def write_back_version(board_id: str, version: str) -> None:
    """编译成功后把 app 描述符里的实际版本回填 config.ini（防手改遗漏造成倒退）。

    行级替换而非 parser.write() 全量重写——后者会抹掉文件里所有 # 注释。
    只改目标段里的 version 值，行的其余部分（行内注释、缩进）原样保留；
    段不存在或段里没有 version 行时追加到段尾。文件不存在则按模板新建。
    """
    if not version:
        return

    # 已一致则不动文件（含行内注释场景：解析后比较，而非文本比较）
    try:
        current = read_board_version(board_id)
    except Exception:
        current = None
    if current == version:
        return

    if not VERSIONS_INI.is_file():
        # 文件不存在：按最小模板新建（顶层说明见 config.ini 模板注释）
        template = (
            "# hardware/sets 版本号集中管理（build.py 自动维护）\n"
            "# 优先级：[<版型id>] > [default]\n\n"
            f"[{board_id}]\nversion = {version}\n"
        )
        try:
            VERSIONS_INI.write_text(template, encoding="utf-8", newline="\n")
            notice_ok(f"config.ini 不存在，已按 [{board_id}] version = {version} 新建")
        except OSError as error:
            notice_warn(f"config.ini 新建失败（不影响产物）: {error}")
        return

    original = read_text_preserve(VERSIONS_INI)
    lines = original.split("\n")
    section_line = -1
    target_line = -1
    next_section_line = len(lines)
    in_target = False
    for idx, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if in_target:
                next_section_line = idx
                break
            in_target = stripped == f"[{board_id}]"
            if in_target:
                section_line = idx
        elif in_target and _VERSION_LINE_PATTERN.match(stripped):
            target_line = idx

    if section_line < 0:
        # 段不存在：追加到文件尾（保持与前段空一行）
        if lines and lines[-1].strip():
            lines.append("")
        lines.append(f"[{board_id}]")
        lines.append(f"version = {version}")
        action = "追加段"
    elif target_line >= 0:
        match = _VERSION_LINE_PATTERN.match(lines[target_line].strip())
        # 只换值，保留行内注释与前缀空白
        lines[target_line] = (
            lines[target_line][: len(lines[target_line]) - len(lines[target_line].lstrip())]
            + match.group(1) + version + match.group(3)
        )
        action = "更新"
    else:
        # 段在但无 version 行：插到段头后
        lines.insert(section_line + 1, f"version = {version}")
        action = "补行"

    new_text = "\n".join(lines)
    if original.endswith("\n") and not new_text.endswith("\n"):
        new_text += "\n"
    if "\r\n" in original:
        new_text = new_text.replace("\n", "\r\n")
    try:
        write_text_preserve(VERSIONS_INI, new_text)
        notice_ok(f"config.ini 已回填（{action}）[{board_id}] version = {version}")
    except OSError as error:
        notice_warn(f"config.ini 回填失败（不影响产物）: {error}")


