def main(argv: Optional[list[str]] = None) -> int:
    global _USE_COLOR, _PYTHON_OVERRIDE, _IDF_ENV_CACHE
    args = parse_args(argv)
    _init_stdio()
    _USE_COLOR = not args.no_color and bool(getattr(sys.stdout, "isatty", lambda: False)())
    if _USE_COLOR:
        _enable_windows_ansi()

    if args.python:
        _PYTHON_OVERRIDE = args.python
        _IDF_ENV_CACHE = None

    say(rule("="))
    say(bold("小智固件多版型编译 (hardware/sets/build.py)"))
    say(rule("="))

    boards, broken = discover_boards()
    print_board_list(boards, broken)

    if args.list:
        return EXIT_OK if boards else EXIT_ERROR

    if not boards:
        notice_bad("没有可用版型，请先在 boards/<id>/ 下按 SPEC.md 补齐 set.json 等文件")
