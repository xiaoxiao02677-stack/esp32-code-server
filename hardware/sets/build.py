def _read_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _validate(board_id: str, data: dict[str, Any]) -> tuple[list[str], list[str]]:
    """返回 (致命错误列表, 警告列表)。致命错误非空则该版型不可用。"""
    fatal: list[str] = []
    warn: list[str] = []

    missing = [key for key in REQUIRED_FIELDS if key not in data]
    if missing:
        fatal.append("缺少必填字段: " + ", ".join(missing))
        return fatal, warn

    if not isinstance(data["id"], str) or data["id"] != board_id:
        fatal.append(f"字段 id={data['id']!r} 与目录名 {board_id!r} 不一致")

    manufacturer = data["manufacturer"]
    if not isinstance(manufacturer, str) or not manufacturer:
        fatal.append("manufacturer 必须是非空字符串")
        manufacturer = ""

    board_dir = data["board_dir"]
    if not isinstance(board_dir, str) or "/" not in board_dir:
        fatal.append(f"board_dir={board_dir!r} 必须是 '制造商/<id>' 形式（如 yuhe/{board_id}）")
    elif manufacturer and board_dir.split("/")[0] != manufacturer:
        fatal.append(f"board_dir 首段 {board_dir.split('/')[0]!r} 与 manufacturer {manufacturer!r} 不一致")
    elif board_dir.split("/")[-1] != board_id:
        warn.append(f"board_dir 末段 {board_dir.split('/')[-1]!r} 与 id {board_id!r} 不一致")

    if manufacturer and manufacturer != "yuhe":
        warn.append(f"manufacturer={manufacturer!r}，规范要求固定为 'yuhe'")

    symbol = data["kconfig_symbol"]
    if not isinstance(symbol, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*", symbol):
        fatal.append(
            f"kconfig_symbol={symbol!r} 非法：需全大写、字母开头、只含 A-Z 0-9 _、不带 CONFIG_ 前缀"
        )

    target = data["target"]
    if not isinstance(target, str) or not re.fullmatch(r"[a-z0-9]+", target):
        fatal.append(f"target={target!r} 非法：需小写芯片名（如 esp32s3）")

    if not isinstance(data["pins_verified"], bool):
        fatal.append(f"pins_verified={data['pins_verified']!r} 必须是 true / false")

    append = data.get("sdkconfig_append", [])
    if not isinstance(append, list) or not all(isinstance(item, str) for item in append):
        fatal.append("sdkconfig_append 必须是字符串数组")
        data["sdkconfig_append"] = []

    extra = data.get("cmake_extra", [])
    if not isinstance(extra, list) or not all(isinstance(item, str) for item in extra):
        warn.append("cmake_extra 不是字符串数组，已忽略")
        data["cmake_extra"] = []

    emoji = data.get("emoji_collection", DEFAULT_EMOJI_COLLECTION)
    if not isinstance(emoji, str) or not emoji:
        warn.append(f"emoji_collection 非法，回退为 {DEFAULT_EMOJI_COLLECTION}")
        data["emoji_collection"] = DEFAULT_EMOJI_COLLECTION

    return fatal, warn


def discover_boards() -> tuple[list[dict[str, Any]], list[tuple[str, list[str]]]]:
    """扫描 boards/*/set.json。返回 (可用版型, [(目录名, 错误列表), ...])。"""
    boards: list[dict[str, Any]] = []
    broken: list[tuple[str, list[str]]] = []

    if not BOARDS_ROOT.is_dir():
        notice_bad(f"版型目录不存在: {BOARDS_ROOT}")
        return boards, broken

    for entry in sorted(BOARDS_ROOT.iterdir(), key=lambda item: item.name):
        if not entry.is_dir() or entry.name.startswith((".", "_")):
            continue
        set_json = entry / "set.json"
        if not set_json.is_file():
            broken.append((entry.name, ["缺少 set.json（SPEC.md 第 2 节）"]))
            continue
        try:
            data = _read_json(set_json)
        except Exception as error:  # noqa: BLE001 - 解析失败不能中断其它版型
            broken.append((entry.name, [f"set.json 解析失败: {error}"]))
            continue
        if not isinstance(data, dict):
            broken.append((entry.name, ["set.json 顶层必须是 JSON 对象"]))
            continue

        fatal, warn = _validate(entry.name, data)
        for message in warn:
            notice_warn(f"{entry.name}: {message}")
        if fatal:
            broken.append((entry.name, fatal))
            continue

        for key, default in OPTIONAL_DEFAULTS.items():
            data.setdefault(key, default)
        data["_dir"] = entry
        boards.append(data)

    # 全局唯一性：Kconfig 符号与 build_name 不能撞车
    seen_symbol: dict[str, str] = {}
    seen_name: dict[str, str] = {}
    unique: list[dict[str, Any]] = []
    for board in boards:
        symbol = board["kconfig_symbol"]
        name = board["build_name"]
        if symbol in seen_symbol:
            broken.append((board["id"], [f"kconfig_symbol {symbol} 与版型 {seen_symbol[symbol]} 重复"]))
            continue
        if name in seen_name:
            broken.append((board["id"], [f"build_name {name} 与版型 {seen_name[name]} 重复"]))
            continue
        seen_symbol[symbol] = board["id"]
        seen_name[name] = board["id"]
        unique.append(board)

    return unique, broken


def print_board_list(boards: list[dict[str, Any]], broken: list[tuple[str, list[str]]]) -> None:
    say()
    say(bold(f"可用版型（{len(boards)} 个）"))
    say(rule())
    if not boards:
        say("  （没有可用版型，请先按 SPEC.md 第 7 节新增一个）")
    for index, board in enumerate(boards, start=1):
        flag = "  " if board["pins_verified"] else yellow("[!]")
        say(f"  {index:>2}) {flag} {bold(board['id'])}  {board['name']}")
        say(f"      描述: {board['description']}")
        say(f"      目标: {board['target']}   目录: {board['board_dir']}   "
            f"符号: {board['kconfig_symbol']}")
        say(f"      产物名: {board['build_name']}   "
            f"引脚: {'已验证' if board['pins_verified'] else yellow('未验证')}")
        say()
    if broken:
        say(red(f"以下 {len(broken)} 个版型存在问题，已跳过："))
        for name, errors in broken:
            say(f"  {red('[跳过]')} {name}")
            for message in errors:
                say(f"         - {message}")
        say()


